const fs = require('fs');
const path = require('path');

/**
 * Write .antigravity/gate-X-audit.md into target project
 */
function writeGateAuditReport(projectPath, gateResult) {
  const antigravityDir = path.join(projectPath, '.antigravity');
  if (!fs.existsSync(antigravityDir)) {
    fs.mkdirSync(antigravityDir, { recursive: true });
  }

  const { id, number, name, status, score, findings, stats, stackInfo } = gateResult;
  const fileName = `${id}-audit.md`;
  const filePath = path.join(antigravityDir, fileName);

  const p0s = findings.filter(f => f.severity === 'P0');
  const p1s = findings.filter(f => f.severity === 'P1');
  const p2s = findings.filter(f => f.severity === 'P2');
  const passed = findings.filter(f => f.severity === 'PASSED');

  const content = `# Antigravity Production Preflight Audit: Gate ${number} - ${name}

> **Audit Generated by LaunchGate Command Center**  
> **Timestamp:** ${new Date().toISOString()}  
> **Target Project:** \`${projectPath}\`  
> **Status:** \`${status.toUpperCase()}\` | **Gate Score:** \`${score}/100\`  
> **Findings Summary:** ${p0s.length} Critical (P0), ${p1s.length} High Risk (P1), ${p2s.length} Hygiene (P2), ${passed.length} Passed Checks

---

## 🧭 Mandatory Antigravity Agent Directives

When addressing this gate report, strictly enforce the following protocols:

1. **Context7 SDK Verification Protocol**:
   - Before modifying, upgrading, or writing code against external libraries or SDKs (e.g., Stripe, Next.js, Supabase, Tailwind, Firebase, Sentry), you MUST use **Context7** tools (\`resolve-library-id\` and \`query-docs\`) to retrieve exact version-specific syntax and interfaces.
   - Never guess API method signatures or rely on outdated assumptions.

2. **Sentry & Observability Protocol**:
   - Follow Sentry preflight standards: ensure all error reporting scrubs sensitive data (passwords, tokens, PII) in \`beforeSend\`, and configure appropriate error boundaries.

3. **Preflight Security Standards**:
   - **Zero-Trust**: Verify server sessions on every mutating endpoint.
   - **BOLA/IDOR Defense**: Scope all database reads/updates by verified \`userId\` / \`tenantId\`.
   - **Secret Isolation**: Ensure private credentials never leak to client environment prefixes.
   - **Non-Destructive**: Maintain backward compatibility and preserve working user flows.

---

## 🚨 Critical Blockers (P0)
${p0s.length === 0 ? '_No P0 Critical Blockers detected._\n' : p0s.map(renderFindingMarkdown).join('\n\n')}

---

## ⚠️ High Risk Anomalies (P1)
${p1s.length === 0 ? '_No P1 High Risk issues detected._\n' : p1s.map(renderFindingMarkdown).join('\n\n')}

---

## 🧹 Maintenance & Hygiene (P2)
${p2s.length === 0 ? '_No P2 Maintenance issues detected._\n' : p2s.map(renderFindingMarkdown).join('\n\n')}

---

## ✅ Passed Checks
${passed.map(p => `- **[PASSED]** ${p.title} (${p.description})`).join('\n')}

---

## 🛠️ Recommended AI Prompt
\`\`\`markdown
Review and fix the findings documented in \`.antigravity/${fileName}\` for Gate ${number} (${name}).
Verify all external SDK method signatures against official documentation, then provide atomic, production-grade code patches for each detected issue.
Ensure no existing business logic or UI state is broken.
\`\`\`
`;

  fs.writeFileSync(filePath, content, 'utf-8');
  return filePath;
}

/**
 * Write .antigravity/gate-X-fix.md with atomic remediation plan
 */
function writeGateFixPlan(projectPath, gateResult, userFixNotes = '') {
  const antigravityDir = path.join(projectPath, '.antigravity');
  if (!fs.existsSync(antigravityDir)) {
    fs.mkdirSync(antigravityDir, { recursive: true });
  }

  const { id, number, name, findings } = gateResult;
  const fileName = `${id}-fix.md`;
  const filePath = path.join(antigravityDir, fileName);

  const actionableFindings = findings.filter(f => f.severity === 'P0' || f.severity === 'P1');

  const content = `# Antigravity Remediation Plan: Gate ${number} - ${name}

> **Generated by LaunchGate Command Center**  
> **Timestamp:** ${new Date().toISOString()}  
> **Target Project:** \`${projectPath}\`  
> **Target Scope:** ${actionableFindings.length} Actionable Items (P0 & P1)

${userFixNotes ? `### Ingested Review Notes:\n${userFixNotes}\n\n---` : ''}

## 📋 Remediation Execution Tasks

${actionableFindings.map((f, idx) => `
### Task ${idx + 1}: Resolve [${f.severity}] in \`${f.file}${f.line ? `:${f.line}` : ''}\`
- **Issue:** ${f.title}
- **Description:** ${f.description}
- **Rule Reference:** ${f.rule || 'LaunchGate Preflight Standard'}
${f.snippet ? `\n**Offending Code:**\n\`\`\`\n${f.snippet}\n\`\`\`\n` : ''}
**Required Fix:**
${f.remediation || 'Refactor code to comply with production preflight standards.'}
`).join('\n\n')}

---

## 🛡️ Verification Gate
After applying all patches:
1. Re-run \`LaunchGate Gate ${number}\` scan.
2. Confirm zero P0 and P1 issues remain.
3. Verify project builds cleanly.
`;

  fs.writeFileSync(filePath, content, 'utf-8');
  return filePath;
}

function renderFindingMarkdown(f) {
  let out = `### [${f.severity}] ${f.title}
- **File:** \`${f.file}${f.line ? `:${f.line}` : ''}\`
- **Impact:** ${f.description}`;

  if (f.snippet) {
    out += `\n- **Detected Snippet:**\n\`\`\`\n${f.snippet}\n\`\`\``;
  }
  if (f.remediation) {
    out += `\n- **Remediation Guideline:**\n> ${f.remediation.replace(/\n/g, '\n> ')}`;
  }
  return out;
}

/**
 * Generate 1-click clipboard prompt for AI audit
 */
function generateAuditPrompt(gateResult, projectPath) {
  const { id, number, name, stats } = gateResult;
  const p0 = stats?.p0 || 0;
  const p1 = stats?.p1 || 0;
  const p2 = stats?.p2 || 0;

  const parts = [];
  if (p0 > 0) parts.push(`${p0} P0 Blocker${p0 > 1 ? 's' : ''}`);
  if (p1 > 0) parts.push(`${p1} P1 High Risk${p1 > 1 ? 's' : ''}`);
  if (p2 > 0 && p0 === 0 && p1 === 0) parts.push(`${p2} P2 Hygiene Warning${p2 > 1 ? 's' : ''}`);

  const reviewSentence = parts.length > 0
    ? `Review the ${parts.join(' and ')} detected.`
    : `All checks passed cleanly. Confirm production readiness and ensure no latent regressions exist.`;

  return `Act as Principal Staff Security & QA Architect. I have run LaunchGate Gate ${number} (${name}) on my project \`${projectPath}\`.
Please inspect \`.antigravity/${id}-audit.md\`.
${reviewSentence}
Verify any third-party SDK method signatures against official documentation, and provide clean, production-ready code fixes for all detected issues.`;
}

/**
 * Generate 1-click clipboard prompt for Antigravity auto-fix
 */
function generateAutoFixPrompt(gateResult, projectPath) {
  const { id, number, name } = gateResult;
  return `Please execute the remediation tasks outlined in \`.antigravity/${id}-fix.md\` for Gate ${number} (${name}).
Apply atomic, drop-in code patches to fix all P0 and P1 vulnerabilities, run typechecks, and confirm all security and reliability standards are met.`;
}

module.exports = {
  writeGateAuditReport,
  writeGateFixPlan,
  generateAuditPrompt,
  generateAutoFixPrompt
};

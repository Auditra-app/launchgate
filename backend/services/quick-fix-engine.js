function getApplicableFix(findingRule) {
  const normRule = (findingRule || '').toLowerCase();
  for (const [fixId, fix] of Object.entries(QUICK_FIXES)) {
    if (fix.applicableRules.some(r => normRule.includes(r.toLowerCase()))) {
      return { fixId, ...fix };
    }
  }
  return null;
}

function applyQuickFix(projectPath, fixId) {
  const fix = QUICK_FIXES[fixId];
  if (!fix) {
    throw new Error(`Unknown quick fix ID: ${fixId}`);
  }

  const { result, backup, diffPreview, changedFiles, rollbackToken } = captureAndBackupWrites(
    projectPath,
    `Quick Fix: ${fix.title || fixId}`,
    () => fix.apply(projectPath)
  );

  return {
    ...(result || {}),
    backup,
    diffPreview,
    changedFiles,
    rollbackToken
  };
}

function revertQuickFix(token) {
  const entry = rollbackStore.get(token);
  if (!entry) {
    return { success: false, message: 'Unknown or expired rollback token.' };
  }

  if (entry.backupId) {
    return restoreBackup(entry.projectPath, entry.backupId);
  }

  const reverted = [];
  const failed = [];
  for (const file of entry.files || []) {
    try {
      if (!file.existed) {
        if (fs.existsSync(file.abs)) fs.unlinkSync(file.abs);
      } else if (file.before !== null) {
        fs.writeFileSync(file.abs, file.before, 'utf8');
      } else {
        failed.push({
          file: path.relative(entry.projectPath, file.abs).replace(/\\/g, '/'),
          error: 'Original content could not be captured; file left unchanged.'
        });
        continue;
      }
      reverted.push(path.relative(entry.projectPath, file.abs).replace(/\\/g, '/'));
    } catch (err) {
      failed.push({
        file: path.relative(entry.projectPath, file.abs).replace(/\\/g, '/'),
        error: err.message
      });
    }
  }

  rollbackStore.delete(token);
  return { success: failed.length === 0, reverted, failed };
}

